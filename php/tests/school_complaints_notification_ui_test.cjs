'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const src=fs.readFileSync(path.join(root,'app/assets/school-complaints-admin.js'),'utf8');
const begin=src.indexOf('const noticeStages='),end=src.indexOf('function Module(',begin);
assert.ok(begin>=0&&end>begin,'notification settings component is present');
const h=(type,props,...children)=>({type,props:props||{},children});
const ctx={h,fa:x=>String(x)};
vm.runInNewContext(src.slice(begin,end)+'\nthis.NotificationSettings=NotificationSettings;',ctx);
let value={};
const flatten=(node)=>Array.isArray(node)?node.flatMap(flatten):node&&typeof node==='object'&&node.type?[node,...flatten(node.children)]:[];
const render=()=>flatten(ctx.NotificationSettings({value,onChange:v=>{value=v;}}));
let nodes=render();
let boxes=nodes.filter(x=>x.type==='input'&&x.props.type==='checkbox');
assert.equal(boxes.length,6*4*2,'each stage has four audiences and two independent delivery channels');
assert.ok(boxes.every(x=>x.props.checked===false),'all delivery rules must default to OFF');
const chosen=boxes.find(x=>x.props['aria-label']==='ثبت اولیه شکایت، شاکی، پیامک نگین');
assert.ok(chosen,'explicit per-channel accessible name');
chosen.props.onChange({target:{checked:true}});
nodes=render();boxes=nodes.filter(x=>x.type==='input'&&x.props.type==='checkbox');
assert.equal(boxes.filter(x=>x.props.checked).length,1,'setting one channel never enables others');
const bale=boxes.find(x=>x.props['aria-label']==='ثبت اولیه شکایت، شاکی، ربات بله');
assert.equal(bale.props.checked,false,'Bale is independent of SMS');
bale.props.onChange({target:{checked:true}});
assert.equal(value.created.complainant.sms,true);
assert.equal(value.created.complainant.bale,true);
assert.ok(!value.close,'unrelated stage is unchanged');
const login=fs.readFileSync(path.join(root,'app/assets/login-premium.js'),'utf8');
assert.ok(login.includes("complaints.href='/school-complaints-portal'"),'main login entry links to scoped operator portal');
const css=fs.readFileSync(path.join(root,'app/assets/school-complaints-admin.css'),'utf8');
assert.ok(css.includes('.sc-notification-switch:focus-within'),'keyboard toggles have focus indication');
console.log('PASS notification configuration UI: 48 independent switches, opt-in default, focus and scoped login');
