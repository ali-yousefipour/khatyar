const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const workflow = fs.readFileSync(path.join(__dirname, '../../.github/workflows/deploy-php.yml'), 'utf8');
const lines = workflow.split(/\r?\n/);
const protectedChecks = lines.filter(line => line.includes('[ "${rel}" = "lib/Db.php" ]'));
assert.equal(protectedChecks.length, 2);
for (const check of protectedChecks) assert.ok(check.includes('"lib/OrgChart.php"'));
for (const check of protectedChecks) assert.ok(check.includes('"lib/EmploymentAttendance.php"'));
const installerCheck = lines.find(line => line.includes('[ -f deploy-payload/lib/Db.php ]'));
assert.ok(installerCheck.includes('[ -f deploy-payload/lib/OrgChart.php ]'));
assert.ok(installerCheck.includes('[ -f deploy-payload/lib/EmploymentAttendance.php ]'));
const staging = lines.find(line => line.includes('for name in ') && line.includes('OrgChart.php'));
assert.ok(staging.includes('OrgChart.php'));
assert.ok(staging.includes('EmploymentAttendance.php'));
const reconciledFiles = lines.find(line => line.trim().startsWith('for rel in app/index.php'));
assert.ok(reconciledFiles && reconciledFiles.includes('lib/EmploymentAttendance.php') && reconciledFiles.includes('lib/OrgChart.php') && reconciledFiles.includes('app/panel.html'), 'required report libraries and panel must remain in forced production reconciliation outside the rolling commit window');
const dependency = workflow.indexOf("'OrgChart.php' => 'OrgChart.php'");
const routes = workflow.indexOf("'routes.php' => 'routes.php'");
assert.ok(dependency > 0 && dependency < routes);
assert.ok(workflow.indexOf("'EmploymentAttendance.php' => 'EmploymentAttendance.php'") < routes);
const frontController = fs.readFileSync(path.join(__dirname, '../app/index.php'), 'utf8');
assert.ok(!frontController.includes('require_once "$ROOT/lib/EmploymentAttendance.php";'), 'report-only dependency must not break login during partial deployment');
assert.ok(frontController.indexOf("$attendanceRoute['fn']=static function") < frontController.indexOf("require_once dirname(__DIR__).'/lib/EmploymentAttendance.php';"));
assert.ok(workflow.includes('hash_equals(\\$token'));
assert.ok(workflow.includes('hash_equals(\\$srcSha, \\$dstSha)'));
const chartSync=fs.readFileSync(path.join(__dirname,'../lib/ZoneChartSync.php'),'utf8');
const chartSyncUI=fs.readFileSync(path.join(__dirname,'../app/assets/zone-chart-sync.js'),'utf8');
const panel=fs.readFileSync(path.join(__dirname,'../app/panel.html'),'utf8');
assert.match(chartSync,/OrgChart::defaultEdges\(/,'zone synchronization uses live regional edges');
assert.match(chartSyncUI,/:scope > h4 > span:first-child/,'region action must select actual region name, not all action buttons');
assert.match(panel,/zone-chart-sync\.js\?v=/,'production panel must load region sync control');
assert.ok(workflow.includes("'ZoneChartSync.php' => 'ZoneChartSync.php'"),'protected PHP installer includes zone sync');
assert.ok(workflow.includes('for name in Db.php Jwt.php Http.php KhatyarFormsSchema.php WorkContracts.php RegionalTeam.php OrgChart.php ZoneChartSync.php'),'zone sync host install checksum verified');
assert.ok(workflow.includes('lib/OrgChart.php lib/ZoneChartSync.php lib/Push.php'),'zone sync included in forced reconciliation');

console.log('PASS OrgChart deployment: protected FTP paths, staged PHP installer, dependency before routes, token check and checksum verification');
