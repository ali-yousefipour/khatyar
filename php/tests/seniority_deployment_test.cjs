const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const workflow = fs.readFileSync(path.join(root, '.github/workflows/deploy-php.yml'), 'utf8');
const lines = workflow.split(/\r?\n/);
const checks = lines.filter(line => line.includes('[ "${rel}" = "lib/Db.php" ]'));
assert.equal(checks.length, 2);
for (const check of checks) assert.ok(check.includes('"lib/Seniority.php"'));
assert.ok(lines.find(line => line.includes('[ -f deploy-payload/lib/Db.php ]')).includes('[ -f deploy-payload/lib/Seniority.php ]'));
assert.ok(lines.find(line => line.includes('for name in Db.php Http.php')).includes('Seniority.php'));
assert.ok(workflow.indexOf("'Seniority.php' => 'Seniority.php'") < workflow.indexOf("'routes.php' => 'routes.php'"));
const integrity = fs.readFileSync(path.join(root, '.github/workflows/project-integrity.yml'), 'utf8');
assert.ok(integrity.includes('node php/tests/seniority_ui_test.cjs'));
assert.ok(integrity.includes('php php/tests/seniority_test.php'));
assert.ok(workflow.includes('for rel in app/panel.html app/assets/panel.bundle.js app/assets/school-service-admin.js; do'));
assert.ok(workflow.includes('cmp -s "${local_path}" "${remote_path}"'));
assert.ok(workflow.includes("grep -q 'panel.bundle.js'"));
assert.ok(!workflow.includes("grep -q 'assets/panel.bundle.js?v=20261015.4'"));
const html = fs.readFileSync(path.join(root, 'php/app/panel.html'), 'utf8');
const bundleReference = html.match(/assets\/panel\.bundle\.js\?v=[^"\s]+/);
assert.ok(bundleReference, 'Panel references a cache-versioned bundle');
assert.ok(fs.existsSync(path.join(root, 'php/app', bundleReference[0].split('?')[0])), 'Referenced bundle exists');
const source = fs.readFileSync(path.join(root, 'php/tools/panel_source.jsx'), 'utf8');
assert.ok(source.includes('["seniority","سنوات نیروها"]'));
const menuLiteral=source.match(/const PANEL_MENU_SECTIONS=(\[[\s\S]*?\n\]);/);
assert.ok(menuLiteral, 'Canonical sidebar categories exist');
const menuSections=JSON.parse(menuLiteral[1].replace(/,\s*]/g,']'));
const hrSection=menuSections.find(([title])=>title.includes('منابع انسانی'));
assert.ok(hrSection&&hrSection[1].includes('seniority'), 'Seniority remains in the HR category');
assert.equal(menuSections.flatMap(([,keys])=>keys).filter(key=>key==='seniority').length,1,'Seniority has exactly one canonical menu entry');
assert.equal((source.match(/seniority:\{t:"سنوات نیروها"/g) || []).length, 1);
const php = fs.readFileSync(path.join(root, 'php/lib/Seniority.php'), 'utf8');
const sql = fs.readFileSync(path.join(root, 'php/db/seniority_schema.sql'), 'utf8');
for (const match of php.matchAll(/Db::run\("(CREATE TABLE IF NOT EXISTS[\s\S]*?)"\);/g)) {
  assert.ok(sql.replace(/\s+/g, ' ').includes(match[1].replace(/\s+/g, ' ')), 'Schema SQL and API must stay identical');
}
console.log('PASS seniority deployment: staged protected library, dependency order, canonical menu, cache key and identical migration schema');
