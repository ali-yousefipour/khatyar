'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const app = fs.readFileSync(path.resolve(__dirname, '../App.js'), 'utf8');
const start = app.indexOf('function RestrictedScreen(');
const end = app.indexOf('function MainStack(', start);
assert.ok(start !== -1 && end > start, 'restricted route wrapper must be present');
const gate = app.slice(start, end);
const keyExpression = gate.match(/const scopeKey=([^;]+);/)?.[1];
assert.ok(keyExpression, 'route grant must be tagged with account identity and role');
const keyFor = (routeName,user) => vm.runInNewContext(keyExpression,{routeName,user,String});
const current = keyFor('Reports',{id:101,role_id:5,level:5});
assert.notEqual(current,keyFor('Reports',{id:102,role_id:5,level:5}),'grants cannot cross accounts');
assert.notEqual(current,keyFor('Reports',{id:101,role_id:4,level:5}),'role changes invalidate the currently displayed grant');
assert.notEqual(current,keyFor('Reports',{id:101,role_id:5,level:4}),'permission level changes invalidate the currently displayed grant');
assert.notEqual(current,keyFor('Requests',{id:101,role_id:5,level:5}),'grants cannot cross routes');
assert.match(gate,/if\(pending\|\|authorizedScope!==scopeKey\)return/,'stale account grants must render loading rather than a protected screen');
assert.match(gate,/setAccess\(null\);setAuthorizedScope\(''\);setPending\(true\)/,'role transitions clear the previous grant');
assert.match(gate,/setAccess\(fresh\);setAuthorizedScope\(scopeKey\);setPending\(false\)/,'fresh grants must carry their identity');
assert.match(gate,/setAccess\(cached\);setAuthorizedScope\(scopeKey\);setPending\(false\)/,'offline caches remain supported but scoped');
assert.match(gate,/\},\[scopeKey,attempt\]\)/,'role, level and account transitions must re-evaluate permissions');
assert.match(gate,/!access\?\.includes\(routeName\)/,'server denied routes must not be rendered');
const auth = fs.readFileSync(path.resolve(__dirname, '../src/auth.js'), 'utf8');
assert.match(auth,/permissionsChanged\)\{\s*await invalidateAppItems\(user\.id\)/,'role-change invalidation remains coupled to authentication');
console.log('PASS route grant scoping: account, role, level, route, cache and server denial');
