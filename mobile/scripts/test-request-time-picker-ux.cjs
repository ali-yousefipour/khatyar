const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const picker = fs.readFileSync(path.resolve(__dirname, '../src/components/TimePicker.js'), 'utf8');
const requests = fs.readFileSync(path.resolve(__dirname, '../src/screens/RequestsScreen.js'), 'utf8');

assert.match(picker, /Array\.from\(\{ length: 24 \}/, 'all 24 hours must be directly selectable');
assert.doesNotMatch(picker, /setPeriod\(|period === 'am'/, 'hour choice must not require switching AM/PM');
assert.match(picker, /Array\.from\(\{length:12\},\(_,i\)=>i\*5\)/, 'five-minute shortcuts cover the full hour');
assert.match(picker, /m > 59/, 'invalid minutes must be rejected');
assert.match(picker, /onSelect\(formatTime\(hour, m\)\)/, 'API must receive unchanged HH:mm format');
assert.match(requests, /label=\{label\} onSelect=\{onPick\}/, 'picker identifies start or end time');
assert.match(picker, /columns: \{ flexDirection: 'row-reverse'/, 'Picker columns retain RTL Android layout');
assert.ok(picker.indexOf('<SpinnerColumn label="دقیقه"') < picker.indexOf('<SpinnerColumn label="ساعت"'), 'With row-reverse on RTL Android, hour appears on the left and minute on the right');
assert.match(picker, /accessibilityLabel=\{'کاهش ' \+ label\} onPress=\{\(\) => change\(-1\)\}/, 'upper spinner control moves to preceding value');
assert.match(picker, /accessibilityLabel=\{'افزایش ' \+ label\} onPress=\{\(\) => change\(1\)\}/, 'lower spinner control moves to following value');
assert.match(picker, /arrow: \{ minHeight: 44/, 'spinner arrows meet Android touch target');
assert.match(picker, /neighbor: \{ minHeight: 44/, 'adjacent time entries meet Android touch target');
assert.match(picker, /behavior=\{Platform.OS === 'ios' \? 'padding' : 'height'\}/, 'keyboard avoidance works on Android');
const jalali = fs.readFileSync(path.resolve(__dirname, '../src/components/JDatePicker.js'), 'utf8');
assert.match(jalali, /const ascii =/, 'Jalali calendar normalizes Persian and Arabic initial digits');
assert.match(jalali, /const parts = ascii\(initial\)/, 'initial string date uses normalized numerals');
assert.match(jalali, /const insets = useSafeAreaInsets\(\)/, 'Jalali picker respects bottom system insets');
assert.equal((jalali.match(/accessibilityRole="tab" accessibilityState=\{\{selected:mode===/g)||[]).length,3,'all calendar modes expose active tab');
assert.match(jalali, /day: \{ width: '13%', minHeight:44/, 'day cells have usable touch height');
const vm = require('node:vm');
const asciiSource = jalali.match(/^const ascii = .*;$/m)?.[0];
const normalizeSource = jalali.match(/function normalizeInitial[\s\S]*?\n}\nfunction j2g/)?.[0]?.replace(/\nfunction j2g$/, '');
assert.ok(asciiSource && normalizeSource, 'Jalali normalization functions must be extractable');
const sandbox = { jToday: () => [1405, 8, 30], Number, String, Array };
vm.createContext(sandbox);
vm.runInContext("const FA='۰۱۲۳۴۵۶۷۸۹';\n" + asciiSource + "\n" + normalizeSource + "\nthis.normalizeInitial=normalizeInitial;", sandbox);
const normalized = sandbox.normalizeInitial('۱۴۰۵/۰۸/۳۰', 1405);
assert.equal(normalized.jy, 1405);
assert.equal(normalized.jm, 8);
assert.equal(normalized.jd, 30);
const arabic = sandbox.normalizeInitial('١٤٠٥-٠٨-٣٠', 1405);
assert.equal(arabic.jy, 1405);
assert.equal(arabic.jm, 8);
assert.equal(arabic.jd, 30);
console.log('PASS request time picker UX and HH:mm contract');
