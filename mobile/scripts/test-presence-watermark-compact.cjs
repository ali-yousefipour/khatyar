'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const code=fs.readFileSync(path.join(__dirname,'../src/VehiclesPhotoCapture.js'),'utf8');
const route=fs.readFileSync(path.join(__dirname,'../../php/lib/presence_reverse_geocode.php'),'utf8');
const api=fs.readFileSync(path.join(__dirname,'../../php/lib/routes.php'),'utf8');
const matchStyle=name=>{
  const m=code.match(new RegExp('^\\s*'+name+':\\s*\\{([^}]+)\\}', 'm'));
  assert.ok(m,'missing '+name+' style');
  return m[1];
};
const box=matchStyle('stampBox'),label=matchStyle('stampTxt'),geo=matchStyle('stampGeo');
assert.match(box,/paddingVertical:\s*5/,'watermark uses minimal vertical inset');
assert.match(box,/paddingHorizontal:\s*7/,'watermark has compact horizontal inset');
assert.doesNotMatch(box,/maxHeight|height:\s*\d{3}/,'no fixed oversized banner height');
assert.match(label,/fontSize:\s*9\b/);
assert.match(label,/lineHeight:\s*13\b/);
assert.match(geo,/fontSize:\s*8\.5/);
assert.match(code,/numberOfLines=\{2\}[^\n]+موقعیت:[^\n]+خیابان:/,'street is printed alongside GPS coords');
assert.match(code,/numberOfLines=\{1\}[^\n]+ایستگاه:/,'nearest station is retained');
assert.match(code,/numberOfLines=\{1\}[^\n]+کاربر:/,'operator and line are retained');
assert.ok(!code.includes('stampDivider:'),'large stamp divider was removed');
assert.match(code,/Location\.reverseGeocodeAsync/,'Android native geocoder');
assert.match(code,/\/my\/reverse-geocode\?lat=/,'rate-limited server OpenStreetMap road resolver');
assert.match(code,/\/geo\/reverse\?lat=/,'existing Neshan map road resolver');
assert.match(code,/Promise\.all\(\[deviceLookup\(\),serverLookup\(\)\]\)/,'independent geocoders run without sequential delay');
assert.match(code,/const resolved=deviceRoad\|\|serverRoad\|\|mapRoad\|\|lastRoad;/,'three sources plus safe local offline cache');
assert.match(code,/haversine\(lat,lng,Number\(stored.lat\),Number\(stored.lng\)\)<=75/,'offline street cache is spatially bounded');
assert.match(code,/Date\.now\(\)-Number\(stored.saved_at\)<24\*60\*60\*1000/,'offline street cache has a one-day TTL');
assert.match(code,/if\(deviceRoad\|\|serverRoad\|\|mapRoad\)await AsyncStorage\.setItem/,'map result is cached for no-network photo capture');
assert.match(code,/source === 'openstreetmap' \? <Text style=\{s.attribution\}>© OpenStreetMap/,'OSM requires proper attribution on image');
assert.match(route,/next_allowed/,'backend keeps rate limiting');
assert.match(api,/route\('GET', '\/api\/geo\/reverse'/,'Neshan route exists');
console.log('PASS photo watermark: compressed RTL metadata with street + GPS and 3 geocoders with bounded offline cache');
