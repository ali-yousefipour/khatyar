'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const migration=fs.readFileSync(path.join(root,'.github/workflows/migrate-khatyar-domain.yml'),'utf8');
const config=fs.readFileSync(path.join(root,'mobile/src/config.js'),'utf8');
const version=fs.readFileSync(path.join(root,'mobile/app.config.js'),'utf8');
assert.match(config,/BUILD_DEFAULT\s*=\s*['"]https:\/\/khat-yar\.ir\/api['"]/);
const packageVersion=JSON.parse(fs.readFileSync(path.join(root,'mobile/package.json'),'utf8')).version;
assert.ok(version.includes("const APP_VERSION = '"+packageVersion+"'"), 'Android release version must match package.json');
assert.match(migration,/Verify new domain, PHP libraries, database and login/);
assert.match(migration,/Verify public signed APK instead of copying it to the web domain/);
assert.match(migration,/khatyar-releases/);
assert.match(migration,/khat-yar\.apk/);
assert.ok(!migration.includes('put $apk -o /khat-yar.ir/releases'), 'APK must not be hosted on the production web domain');
assert.match(migration,/Activate mandatory 2\.0\.2 update after release and domain verification/);
const cutoff=migration.indexOf('Disable legacy API after successful 2.0.2 activation');
const activated=migration.indexOf('Activate mandatory 2.0.2 update after release and domain verification');
assert.ok(cutoff>activated,'legacy shutdown must run only after successfully verified new release');
const legacy=migration.slice(cutoff);
assert.match(legacy,/RewriteRule \^api\(\/\|\$\) - \[G,L\]/,'every legacy API request must return 410');
assert.doesNotMatch(legacy,/REQUEST_URI.*api\/app\/version/,'old APK version endpoint must not remain active');
assert.match(legacy,/test "\$code" = 410/,'cutover must verify legacy API is disabled');
console.log('PASS migration policy: new domain, 2.0.2, validated release, and no legacy API compatibility');
